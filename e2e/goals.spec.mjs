test('Goals remain usable offline through the production service worker', async ({ page, context, app }) => {
  const origin = await productionServer()
  try {
    await app({ data: example(), url: origin.url })
    await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller)), { timeout: 30_000 }).toBe(true)
    await origin.stop()
    await expect(context.request.get(origin.url, { timeout: 2000 })).rejects.toThrow()
    await page.reload()
    await openGoals(page)
    await addTarget(page)
    await page.reload()
    await openGoals(page)
    await expect(page.locator('.goal-achievements')).toContainText('Achieved milestones')
    expect((await readStore(page)).goals[0].achievements).toContainEqual({ value: 90, date: '2026-10-03' })
  } finally { await origin.stop() }
})

test('two-reading reminder uses Blood Pressure validation and returns to the goal after each save', async ({ page, app }) => {
  await app({ data: store() })
  await openGoals(page)
  await page.getByRole('button', { name: 'Add goal', exact: true }).first().click()
  await page.getByRole('combobox', { name: /^Measurement module/ }).selectOption('bloodPressure')
  await page.getByRole('combobox', { name: /^Readings per scheduled day/ }).selectOption('2')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  async function reading(time) {
    await page.getByLabel('Time', { exact: true }).fill(time)
    await page.getByRole('spinbutton').nth(0).fill('120')
    await page.getByRole('spinbutton').nth(1).fill('80')
    await page.getByRole('spinbutton').nth(2).fill('65')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Add reading', exact: true }).click()
  await reading('08:00')
  await expect(page.locator('.goal-record-due')).toContainText('1/2')
  await page.getByRole('button', { name: 'Add reading', exact: true }).click()
  await reading('09:00')
  await expect(page.getByRole('alert')).toBeVisible()
  expect((await readStore(page)).measurements).toHaveLength(1)
  await reading('10:00')
  await expect(page.locator('.goal-record-done')).toContainText('2/2')
  await expect(page.getByRole('button', { name: 'Add reading', exact: true })).toHaveCount(0)
  expect((await readStore(page)).measurements).toHaveLength(2)
})

