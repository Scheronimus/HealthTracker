async function openGoals(page) {
  await page.locator('.module-selector select').selectOption('goals')
  await expect(page.locator('.goals-dashboard')).toBeVisible()
}
async function addTarget(page) {
  await page.getByRole('button', { name: 'Add goal', exact: true }).first().click()
  await page.getByRole('radio', { name: 'Weight target', exact: true }).check()
  await page.getByLabel('Goal start date', { exact: true }).fill('2026-09-27')
  await page.getByRole('spinbutton', { name: 'Target weight (kg)', exact: true }).fill('89')
  await page.getByRole('spinbutton', { name: 'Milestone interval (kg)', exact: true }).fill('0.1')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.goals-dashboard')).toBeVisible()
}
const example = (withSecondDay = true) => store([weight('2026-09-27', 90.1), ...(withSecondDay ? [weight('2026-09-28', 89.9)] : []), weight('2026-10-03', 89.2)])

test('target celebration requires final confirmation and survives rebound and reload', async ({ page, app }) => {
  const data = store([weight('2026-09-24', 92), weight('2026-09-25', 83)])
  data.goals = [{ id: 'completed-target-goal', kind: 'weight', name: '', note: '', startDate: '2026-09-24', startReadingDate: '2026-09-24', start: 92, target: 84, interval: 1, achievements: [], previousAchievements: [] }]
  await page.clock.setFixedTime(new Date('2026-10-02T10:00:00Z'))
  await app({ data })
  await openGoals(page)
  await expect(page.locator('.goal-completion')).toHaveCount(0)
  await page.clock.setFixedTime(new Date('2026-10-03T10:00:00Z'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page.locator('.goal-completion')).toContainText('Target achieved!')
  await expect(page.locator('.goal-completion')).toContainText('Achieved Oct 3, 2026')
  await expect(page.locator('.goal-next')).toHaveCount(0)
  await page.getByRole('button', { name: /Open weight graph/ }).click()
  await page.getByRole('button', { name: 'Add weight', exact: true }).click()
  await page.getByRole('spinbutton').fill('95')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await openGoals(page)
  await expect(page.locator('.goal-completion')).toContainText('Target achieved!')
  await expect(page.locator('.goal-overall progress')).toHaveAttribute('value', '1')
  await page.locator('.goal-title').click()
  await expect(page.locator('.goal-completion')).toBeVisible()
  for (const language of ['en', 'es', 'de', 'fr']) for (const theme of ['light', 'dark']) {
    await page.evaluate(({ language, theme }) => { localStorage.setItem('health-tracker-language', language); localStorage.setItem('health-tracker-theme', theme) }, { language, theme })
    await page.reload()
    await openGoals(page)
    await page.setViewportSize({ width: 320, height: 800 })
    await expect(page.locator('.goal-completion')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  }
})

test('Goals persist, preserve confirmed milestones, use real entry/chart navigation and round-trip backups', async ({ page, app }) => {
  await app({ data: example() })
  await openGoals(page)
  await addTarget(page)
  await expect.poll(async () => (await readStore(page)).goals[0].achievements).toContainEqual({ value: 90, date: '2026-10-03' })
  await page.locator('.goal-achievements summary').click()
  await expect(page.locator('.goal-achievements li')).toContainText('90 kg')
  await page.getByRole('button', { name: /Open weight graph/ }).click()
  await expect(page.locator('.weight-chart')).toBeVisible()
  const targetSwitch = page.getByRole('switch', { name: 'Final target', exact: true })
  const milestoneSwitch = page.getByRole('switch', { name: 'Next milestone', exact: true })
  await expect(targetSwitch).toHaveAttribute('aria-checked', 'true')
  await expect(page.locator('.weight-reference-line.target')).toHaveAttribute('aria-label', 'Final target: 89 kg')
  await expect(page.locator('.weight-reference-line.milestone')).toHaveCount(1)
  await targetSwitch.click()
  await expect(page.locator('.weight-reference-line.milestone')).toHaveCount(1)
  await expect(page.locator('.weight-reference-line.target')).toHaveCount(0)
  await milestoneSwitch.click()
  await expect(page.locator('.weight-reference-line')).toHaveCount(0)
  await targetSwitch.click()
  await expect(page.locator('.weight-reference-line.target')).toHaveCount(1)
  await expect(page.locator('.weight-reference-line.milestone')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('switch', { name: 'Final target', exact: true })).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByRole('switch', { name: 'Next milestone', exact: true })).toHaveAttribute('aria-checked', 'true')
  await openGoals(page)
  await page.getByRole('button', { name: 'Add goal', exact: true }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.goal-record-done')).toContainText('All done')
  await expect(page.getByRole('button', { name: 'Add goal', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Arrange', exact: true }).click()
  await page.locator('.goal-drag-handle').last().focus()
  await page.keyboard.press('ArrowUp')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect.poll(async () => (await readStore(page)).goals[0].kind).toBe('measurement')
  await page.reload()
  await openGoals(page)
  await expect(page.locator('.goal-list > section').first()).toHaveClass(/goal-record-done/)
  await page.clock.setFixedTime(new Date('2026-10-04T10:00:00.000Z'))
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page.locator('.goal-record-due')).toContainText('To do today')
  await page.locator('.goal-record-due').getByRole('button', { name: 'Record weight', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Add weight', exact: true })).toBeVisible()
  await page.getByRole('spinbutton').fill('95')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.goal-record-done')).toContainText('All done')
  const saved = await readStore(page)
  expect(saved.goals.find((goal) => goal.kind === 'weight').achievements).toContainEqual({ value: 90, date: '2026-10-03' })
  await openSettings(page)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download backup', exact: true }).click()
  const stream = await (await download).createReadStream()
  let text = ''
  for await (const chunk of stream) text += chunk.toString()
  expect(JSON.parse(text).data).toEqual(saved)
  page.once('dialog', (dialog) => dialog.accept())
  await page.locator('input[type=file]').setInputFiles({ name: 'goals-backup.json', mimeType: 'application/json', buffer: Buffer.from(text) })
  await expect(page.getByRole('status')).toContainText('Restore complete')
  expect(await readStore(page)).toEqual(saved)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await openGoals(page)
  await page.locator('.goal-title').first().click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add goal', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add goal', exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Weight target', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add goal', exact: true })).toHaveCount(0)
})

